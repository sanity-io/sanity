// Writes `<project>/generated/<stylesheet>.d.ts` for plain (non-module) stylesheets that are only
// imported for their side effects. TypeScript 7 rejects a side-effect import it cannot resolve
// (TS2882), and cmk only types `*.module.css`, so these typings are generated next to cmk's: run
// this after `cmk --clean`, which wipes the directory.
//
// Usage: node src/generateStylesheetTypings.mjs <project> <stylesheet...>
// with stylesheet paths relative to the project, e.g. `src/styles.css`
import {access, mkdir, writeFile} from 'node:fs/promises'
import {dirname, join, resolve} from 'node:path'

const [project, ...stylesheets] = process.argv.slice(2)

if (!project || stylesheets.length === 0) {
  throw new Error('Usage: generateStylesheetTypings.mjs <project> <stylesheet...>')
}

const projectDir = resolve(project)

for (const stylesheet of stylesheets) {
  if (!stylesheet.endsWith('.css') || stylesheet.endsWith('.module.css')) {
    throw new Error(`Expected a plain stylesheet, got ${stylesheet}`)
  }
  // Fails on a stale path instead of typing a stylesheet that no longer exists
  await access(join(projectDir, stylesheet))

  const typings = join(projectDir, 'generated', `${stylesheet}.d.ts`)
  await mkdir(dirname(typings), {recursive: true})
  await writeFile(typings, '// Generated by @repo/css-modules-kit. Do not edit.\nexport {}\n')
}
