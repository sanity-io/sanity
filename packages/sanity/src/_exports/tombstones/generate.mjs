/**
 * Generates type-only export tombstones into the `sanity` package entry barrels.
 *
 * Tombstones are `export declare const Name: never` / `export type Name = never` with a
 * `@deprecated` JSDoc that names the replacement using a public import path (`sanity`,
 * `sanity/structure`, … — never a relative or `src/` path). `declare` emits nothing into
 * the JS bundles (v7's size goal); do not turn these into runtime stubs or re-exports from
 * a separate module — TypeScript emits a runtime re-export for those and the name then
 * fails to link at runtime.
 *
 * Usage (from repo root or this package):
 *   node packages/sanity/src/_exports/tombstones/generate.mjs
 *
 * After editing `manifest.json`, re-run this script, then `pnpm lint:fix` on the touched
 * files. See AGENTS.md ("Export tombstones (v7)").
 */
import {readFileSync, writeFileSync} from 'node:fs'

import {BEGIN, END, listTombstoneTargets} from './entries.mjs'

/** @typedef {import('./entries.mjs').Tombstone} Tombstone */

const HEADER = `${BEGIN}
// Generated by tombstones/generate.mjs from tombstones/manifest.json — do not edit by hand.
// Type-only: every symbol is \`export declare\` / \`export type … = never\`. Nothing here may
// emit runtime JavaScript. See AGENTS.md ("Export tombstones (v7)").
`

/**
 * @param {Tombstone} tombstone
 */
function renderTombstone({name, kind, message}) {
  const doc = `/**\n * @deprecated ${message}\n */`
  if (kind === 'type') {
    return `${doc}\nexport type ${name} = never`
  }
  return `${doc}\nexport declare const ${name}: never`
}

/**
 * @param {Tombstone[]} tombstones
 */
function renderBlock(tombstones) {
  const body = tombstones
    .toSorted((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map(renderTombstone)
    .join('\n')
  return `${HEADER}${body}\n${END}\n`
}

/**
 * @param {string} source
 * @param {string} block
 */
function upsertBlock(source, block) {
  const begin = source.indexOf(BEGIN)
  const end = source.indexOf(END)
  if (begin !== -1 && end !== -1 && end > begin) {
    return `${source.slice(0, begin)}${block.trimEnd()}\n${source.slice(end + END.length).replace(/^\n/, '')}`
  }
  const trimmed = source.replace(/\s*$/, '')
  return `${trimmed}\n\n${block}`
}

for (const {source: path, tombstones} of listTombstoneTargets()) {
  if (!tombstones.length) continue
  const source = readFileSync(path, 'utf8')
  writeFileSync(path, upsertBlock(source, renderBlock(tombstones)))
  console.warn(`updated ${path} (${tombstones.length} tombstones)`)
}
